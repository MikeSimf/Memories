package ru.dndmemory.data.model;

/** Состояние синхронизации, которое показывается в шапке приложения. */
public enum SyncStatus {
    /** Ничего не происходит, всё синхронизировано. */
    IDLE,
    /** Идёт push/pull. */
    SYNCING,
    /** Нет сети — работаем на локальных данных. */
    OFFLINE,
    /** Синхронизация закончилась ошибкой. */
    ERROR,
    /** Есть правки с расхождением, нужно внимание пользователя. */
    CONFLICT
}

package ru.dndmemory.domain;

/** Назначение приглашения. */
public enum InviteMode {
    /** Обычное приглашение: человек входит в аккаунт и присоединяется к кампании. */
    MEMBER,
    /**
     * Приглашение устройства: QR-код выпускает админ, телефон сканирует его и
     * получает долгоживущую сессию без пароля. Пользователь создаётся на сервере.
     */
    DEVICE
}

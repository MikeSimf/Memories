-- Nullable-флаги: TRUE / FALSE / NULL.
ALTER TABLE heroes     ADD COLUMN IF NOT EXISTS alive BOOLEAN;
ALTER TABLE characters ADD COLUMN IF NOT EXISTS alive BOOLEAN;

UPDATE heroes SET alive = CASE life_status
    WHEN 'alive' THEN TRUE WHEN 'dead' THEN FALSE ELSE NULL END
WHERE alive IS NULL;
UPDATE characters SET alive = CASE life_status
    WHEN 'alive' THEN TRUE WHEN 'dead' THEN FALSE ELSE NULL END
WHERE alive IS NULL;

ALTER TABLE items ADD COLUMN IF NOT EXISTS magic BOOLEAN;
ALTER TABLE items ADD COLUMN IF NOT EXISTS has_setting BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE items ADD COLUMN IF NOT EXISTS configured_hero_id UUID REFERENCES heroes (id) ON DELETE SET NULL;
